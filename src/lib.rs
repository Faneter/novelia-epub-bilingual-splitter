//! 把「中日对照」EPUB 拆成两本单语 EPUB。
//!
//! # 源书的排版约定
//!
//! 这套源文件把两种语言**靠内联样式**区分，而不是靠任何标记或目录结构：
//!
//! | | 源文件里的写法 | 数量 |
//! |---|---|---|
//! | 日文原文 | `<p style="opacity:0.4;">…</p>` | 3215 段，淡化显示（原文在下） |
//! | 中文译文 | `<p>…</p>` | 3371 段，正常显示（译文在上） |
//! | 语言无关 | `<p><br /></p>` / `<p><img …/></p>` | 156 段，两本书都要 |
//!
//! 判别式因此只有一条：开标签带不带 `opacity` 样式。之所以敢只靠它：
//!
//! * 38 个正文文件里只有这两种 `<p>`，没有第三种变体；
//! * 中文段落里假名出现 **0** 次；
//! * 414 个 `<ruby>` 注音 **100%** 落在日文段落内。
//!
//! 也就是说切分零歧义、不需要语言识别模型。顺带的好处是中文版自动就没有注音了。
//!
//! # 三个容易踩的坑
//!
//! 1. **必须同时删掉淡化样式**。`opacity:0.4` 在对照排版里表示「这是原文」，
//!    日文版若只删中文段却留着样式，整本书会是淡灰色的。
//! 2. **5 个 CSS 文件全是 0 字节**，样式全部内联，所以不能靠改 CSS 来切换语言。
//! 3. **元数据有错**：源书 `dc:language` 写死成 `zh-CN`（对日文版是错的），
//!    而且两本书必须用不同的 `dc:identifier`，否则阅读器书库会互相覆盖。
//!
//! # 模块分工
//!
//! | 模块 | 职责 |
//! |---|---|
//! | [`lang`] | 语言领域模型（`ja` / `zh-CN` / 书名） |
//! | [`paths`] | 决定读哪个文件、产物叫什么 |
//! | [`epub`] | ZIP 容器层：整包读入 / 写出 |
//! | [`markup`] | XHTML 片段层：切出 `<p>`，不含语言概念 |
//! | [`split`] | 核心：按样式决定段落去留 |
//! | [`metadata`] | OPF / NCX / 章标题改写 |
//! | [`pipeline`] | 编排：组装出一本书 |
//! | [`audit`] | 产物回读自检 |
//!
//! 依赖方向是单向的：`markup` 不认识语言，`split` / `metadata` 都只依赖
//! `lang` + `markup`，`pipeline` 把它们串起来，`main` 只负责打印。

pub mod audit;
pub mod epub;
pub mod lang;
pub mod markup;
pub mod metadata;
pub mod paths;
pub mod pipeline;
pub mod split;

pub use epub::Entry;
pub use lang::Lang;
